"""Investigation report: a 16-section dossier assembled from stored records only, validated before it is stored.

Nothing here is generated by a language model. Every statement is either fixed method text or copied from a stored record with its
reference, so the report can be traced back to evidence. The validator refuses language that assigns fault or legal responsibility.
"""
import re
from datetime import datetime, timezone
from pathlib import Path

from sqlalchemy import select
from sqlalchemy.orm import Session

from app.models import (Actor, ActorLink, AuditLog, Case, Contradiction, Corroboration, Event, EvidenceFile, GapRecord, InvestigationFinding,
                        ModelRun, ReconstructionScenario, SensorSource, Trajectory, Witness, WitnessClaim, WitnessStatement)

REPORT_VERSION = "1"
BANNED = [r"\bat fault\b", r"\bguilty\b", r"\bliab(le|ility)\b", r"\bnegligen\w*", r"\bblame\w*", r"\bcaused by\b", r"\bresponsible for the (accident|collision|crash)\b",
          r"\bdriver error\b", r"\bcriminal\b", r"\bculpab\w*", r"\bproves? that\b", r"\bconclusively\b", r"\bundoubtedly\b"]
SECTIONS = ["Case overview", "Purpose and limits of this report", "Evidence inventory", "Methods and models", "Time synchronization", "Vehicles and people (identity decisions)",
            "Reconstructed timeline", "Direct observations and machine detections", "Witness statements and claims", "Sensor data", "Corroborations", "Contradictions",
            "Gaps and missing evidence", "Trajectories", "Inferences and alternatives", "Open questions and suggested next steps"]
LIMITS = ("This report supports an investigation. It does not determine fault, guilt or legal responsibility, and it must be reviewed by a qualified investigator before "
          "any use. Machine detections are candidates, witness statements are testimony, and inferences are possibilities that are listed with alternatives. "
          "Where evidence is missing or sources cannot be related in time, the report says so instead of filling the gap.")


def _ms(v):
    return None if v is None else round(v / 1000, 2)


def build(db: Session, case: Case, scn: ReconstructionScenario, who: str) -> dict:
    evs = list(db.execute(select(EvidenceFile).where(EvidenceFile.case_id == case.id).order_by(EvidenceFile.uploaded_at)).scalars())
    label = {e.id: f"{e.kind} “{e.original_filename}”" for e in evs}
    events = {e.id: e for e in db.execute(select(Event).where(Event.scenario_id == scn.id)).scalars()}
    actors = {a.id: a for a in db.execute(select(Actor).where(Actor.case_id == case.id)).scalars()}
    cons = list(db.execute(select(Contradiction).where(Contradiction.scenario_id == scn.id)).scalars())
    crbs = list(db.execute(select(Corroboration).where(Corroboration.scenario_id == scn.id)).scalars())
    gaps = list(db.execute(select(GapRecord).where(GapRecord.scenario_id == scn.id)).scalars())
    finds = list(db.execute(select(InvestigationFinding).where(InvestigationFinding.scenario_id == scn.id)).scalars())
    sol = (scn.assumptions or {}).get("sync_solution") or {}
    synthetic = any(e.synthetic for e in evs)
    ordered = sorted(events.values(), key=lambda e: (e.start_case_ms is None, e.start_case_ms or 0, e.id))

    def ev_ref(e: Event):
        return {"event_id": e.id, "title": e.title, "category": e.category, "time_s": _ms(e.start_case_ms), "end_s": _ms(e.end_case_ms),
                "uncertainty_s": _ms(e.uncertainty_ms) if e.start_case_ms is not None else None, "source": label.get(e.source_id, "reconstruction engine"),
                "actor": actors[e.actor_id].label if e.actor_id in actors else None}

    sec: list[dict] = []
    add = lambda title, body: sec.append({"number": len(sec) + 1, "title": title} | body)  # noqa: E731
    add(SECTIONS[0], {"facts": {"case_code": case.code, "title": case.title, "designation": case.designation, "scenario": scn.name, "scenario_id": scn.id,
                                "baseline": scn.is_baseline, "generated": datetime.now(timezone.utc).isoformat(timespec="seconds"), "prepared_by": who,
                                "data_designation": "SYNTHETIC DATA: every item in this report was generated for demonstration" if synthetic else "contains no synthetic data"},
                      "assumptions": {k: (scn.assumptions or {}).get(k) for k in ("edge_offsets", "exclude_edges", "reference", "unconfirm_links")}})
    add(SECTIONS[1], {"text": LIMITS})
    add(SECTIONS[2], {"items": [{"evidence_id": e.id, "kind": e.kind, "file": e.original_filename, "sha256": e.sha256, "size_bytes": e.size_bytes, "synthetic": e.synthetic,
                                 "status": e.status, "uploaded_by": e.uploaded_by} for e in evs]})
    runs = list(db.execute(select(ModelRun).where(ModelRun.case_id == case.id).order_by(ModelRun.started_at)).scalars())
    seen, methods = set(), []
    for r in runs:
        k = (r.stage, r.model_id, r.model_version)
        if k not in seen:
            seen.add(k)
            methods.append({"stage": r.stage, "model": r.model_id, "version": r.model_version, "device": r.device, "status": r.status,
                            "note": "boxes come from a synthetic world model, not a detector" if str(r.model_id).startswith("oracle:") else None})
    add(SECTIONS[3], {"runs": methods, "engine": {"version": (scn.assumptions or {}).get("engine_version"), "rules_version": (scn.assumptions or {}).get("rules_version")},
                      "text": "Events come from deterministic rules over stored detections, tracks, sensor rows and witness claims. No model decides a contradiction, a corroboration or a gap."})
    add(SECTIONS[4], {"groups": sol.get("groups", []), "unsynchronized_sources": [label.get(i, i) for i in sol.get("unsynchronized", [])],
                      "inconsistencies": sol.get("inconsistencies", []),
                      "text": "Times below are on one case clock only for sources joined by a recorded clock relation. Other sources are listed separately and are never ordered against them."})
    links = list(db.execute(select(ActorLink).where(ActorLink.actor_id.in_(list(actors) or [""]))).scalars())
    add(SECTIONS[5], {"actors": [{"id": a.id, "label": a.label, "kind": a.kind, "confirmed_links": [{"type": l.ref_type, "ref": l.ref_id, "decided_by": l.decided_by, "basis": l.basis}
                                                                                           for l in links if l.actor_id == a.id and l.status == "confirmed"],
                                    "candidate_links": sum(1 for l in links if l.actor_id == a.id and l.status == "candidate")} for a in actors.values()],
                      "text": "Only links confirmed by an investigator are used to compare sources. Candidate links are not."})
    add(SECTIONS[6], {"entries": [ev_ref(e) for e in ordered if e.start_case_ms is not None],
                      "unplaced": [ev_ref(e) for e in ordered if e.start_case_ms is None],
                      "text": "Entries are ordered by case time. Each time has an uncertainty. Unplaced entries have no time that can be related to the others."})
    add(SECTIONS[7], {"items": [ev_ref(e) | {"observations": {k: v for k, v in (e.observations or {}).items() if k in ("maneuver", "net_heading_change_deg", "coordinate_frame", "min_gap_in_diagonals")}}
                                for e in ordered if e.category in ("direct_observation", "machine_detection") and e.source_type.startswith("video")],
                      "text": "Machine detections are candidates in image space (pixels). They are not measurements of distance or speed."})
    claims = []
    for c, st, w in db.execute(select(WitnessClaim, WitnessStatement, Witness).join(WitnessStatement, WitnessClaim.statement_id == WitnessStatement.id)
                               .join(Witness, WitnessStatement.witness_id == Witness.id).where(Witness.case_id == case.id)):
        claims.append({"witness": w.label, "quote": c.source_text, "span": [c.char_start, c.char_end], "extraction": c.extraction_status, "certainty": c.certainty,
                       "time_description": c.time_description, "synthetic": st.synthetic})
    add(SECTIONS[8], {"claims": claims, "text": "Quotes are verbatim. A claim is testimony; it is not verified by being listed here."})
    add(SECTIONS[9], {"items": [ev_ref(e) for e in ordered if e.source_type == "sensor"], "sources": [{"evidence": label.get(s.evidence_id), "units": s.units, "synthetic": s.synthetic}
                                                                                                    for s in db.execute(select(SensorSource).where(SensorSource.case_id == case.id)).scalars()]})
    add(SECTIONS[10], {"items": [{"id": c.id, "rule": c.rule_id, "text": c.explanation_template, "independent": c.independent, "independence": c.independence_reason,
                                  "events": c.events, "review": c.review_status} for c in crbs], "text": "Agreement of independent sources raises plausibility; it does not prove an event."})
    add(SECTIONS[11], {"items": [{"id": c.id, "rule": c.rule_id, "strength": c.strength, "text": c.explanation_template, "events": [c.event_a, c.event_b],
                                  "benign_explanations": (c.basis or {}).get("benign_explanations"), "unresolved": c.unresolved_questions, "review": c.review_status} for c in cons],
                       "text": "A contradiction means two sources describe the same thing differently. This report does not say which source is right."})
    add(SECTIONS[12], {"items": [{"id": g.id, "type": g.gap_type, "scope": g.scope, "details": g.details, "recommendation": g.recommendation, "refs": g.refs} for g in gaps]})
    traj = list(db.execute(select(Trajectory).where(Trajectory.scenario_id == scn.id)).scalars())
    add(SECTIONS[13], {"items": [{"id": t.id, "actor": actors[t.actor_id].label if t.actor_id in actors else None, "frame": t.frame, "points": len(t.points), "note": t.calibration_note,
                                  "track": (t.track_ref or {}).get("track_id")} for t in traj],
                       "text": "Image trajectories are pixels. Ground-plane trajectories exist only for calibrated fixed cameras and carry per-point uncertainty."})
    add(SECTIONS[14], {"items": [ev_ref(e) | {"statement": (e.inference or {}).get("statement"), "premises": (e.inference or {}).get("premises"), "alternatives": (e.inference or {}).get("alternatives")}
                                 for e in ordered if e.category == "inference"], "text": "Inferences are possibilities derived by a registered rule. Alternatives are always listed."})
    oq = [f for f in finds if f.kind == "open_question"]
    add(SECTIONS[15], {"open_questions": [{"id": f.id, "text": f.text, "refs": f.ref_ids, "review": f.review_status} for f in oq],
                       "recommendations": sorted({g.recommendation for g in gaps}),
                       "review_status": {"findings": len(finds), "reviewed": sum(1 for f in finds if f.review_status == "reviewed"), "disputed": sum(1 for f in finds if f.review_status == "disputed"),
                                         "unreviewed": sum(1 for f in finds if f.review_status == "unreviewed")}})
    return {"report_version": REPORT_VERSION, "case_id": case.id, "scenario_id": scn.id, "synthetic": synthetic, "sections": sec}


def _strings(x):
    if isinstance(x, str):
        yield x
    elif isinstance(x, dict):
        for k, v in x.items():
            if k not in ("sha256",):
                yield from _strings(v)
    elif isinstance(x, list):
        for v in x:
            yield from _strings(v)


def validate(content: dict) -> dict:
    """Checks that must hold before a report is stored. A failed check is reported, never silently fixed."""
    checks = []
    def chk(name, ok, detail=""):
        checks.append({"check": name, "passed": bool(ok), "detail": detail if not ok else ""})
    secs = content["sections"]
    chk("sixteen sections in order", [s["title"] for s in secs] == SECTIONS)
    text = " ".join(_strings(content)).lower()
    hits = [p for p in BANNED if re.search(p, text, re.I)]
    chk("no language assigning fault or legal responsibility", not hits, f"matched: {hits}")
    by = {s["title"]: s for s in secs}
    chk("synthetic data is labelled", not content["synthetic"] or "SYNTHETIC" in by[SECTIONS[0]]["facts"]["data_designation"])
    chk("every timeline entry names its source and uncertainty", all(e["source"] and (e["uncertainty_s"] is not None) for e in by[SECTIONS[6]]["entries"]))
    chk("unplaced entries carry no time", all(e["time_s"] is None for e in by[SECTIONS[6]]["unplaced"]))
    chk("every inference lists premises and alternatives", all(i["premises"] and i["alternatives"] for i in by[SECTIONS[14]]["items"]))
    chk("every contradiction cites two events and benign explanations", all(len(c["events"]) == 2 and c["benign_explanations"] for c in by[SECTIONS[11]]["items"]))
    chk("every corroboration states independence", all(c["independence"] for c in by[SECTIONS[10]]["items"]))
    chk("every gap has a recommendation and a reference", all(g["recommendation"] and g["refs"] for g in by[SECTIONS[12]]["items"]))
    chk("limits section present", "does not determine fault" in by[SECTIONS[1]]["text"])
    return {"passed": all(c["passed"] for c in checks), "checks": checks}


def to_markdown(content: dict) -> str:
    out = []
    f = content["sections"][0]["facts"]
    out += [f"# Investigation report: {f['title']}", "", f"**{f['data_designation']}**", "", f"Case {f['case_code']} · scenario “{f['scenario']}” · generated {f['generated']}", ""]
    for s in content["sections"]:
        out += [f"## {s['number']}. {s['title']}", ""]
        if s.get("text"):
            out += [s["text"], ""]
        for key in ("entries", "unplaced", "items", "claims", "actors", "runs", "open_questions"):
            rows = s.get(key)
            if not rows:
                continue
            if key == "unplaced":
                out += ["**Not placed on the case clock:**", ""]
            for r in rows:
                if "title" in r and "event_id" in r:
                    t = f"{r['time_s']:.2f} s ±{r['uncertainty_s']:.2f}" if r["time_s"] is not None else "no usable time"
                    out.append(f"- [{t}] {r['title']} — *{r['source']}*" + (f" · {r['actor']}" if r.get("actor") else "") + (f"\n  - alternatives: {'; '.join(r['alternatives'])}" if r.get("alternatives") else ""))
                elif "quote" in r:
                    out.append(f"- {r['witness']}: “{r['quote']}” ({r['certainty']}{', time: ' + r['time_description'] if r.get('time_description') else ''})")
                elif "label" in r:
                    out.append(f"- {r['label']} ({r['kind']}); confirmed links: {len(r['confirmed_links'])}; candidate links not used: {r['candidate_links']}")
                elif "text" in r and "rule" in r:
                    out.append(f"- **{r['rule']}**{' (' + r['strength'] + ')' if r.get('strength') else ''}: {r['text']}")
                elif "recommendation" in r:
                    out.append(f"- *{r['type'].replace('_', ' ')}*: {r['recommendation']}")
                elif "file" in r:
                    out.append(f"- {r['kind']} `{r['file']}` · sha256 `{r['sha256'][:16]}…` · {'synthetic' if r['synthetic'] else 'not synthetic'}")
                elif "stage" in r:
                    out.append(f"- {r['stage']}: {r['model']} {r['version']}" + (f" — {r['note']}" if r.get("note") else ""))
                elif "text" in r:
                    out.append(f"- {r['text']}")
                elif "frame" in r:
                    out.append(f"- {r['actor'] or 'unidentified'} · {r['frame']} · {r['points']} points — {r['note']}")
                else:
                    out.append(f"- {r}")
            out.append("")
        if s["title"] == SECTIONS[4]:
            out += [f"- Groups: {len(s['groups'])}; unsynchronized sources: {', '.join(s['unsynchronized_sources']) or 'none'}", ""]
        if s["title"] == SECTIONS[15]:
            out += ["**Suggested next steps:**", ""] + [f"- {r}" for r in s["recommendations"]] + [""]
    return "\n".join(out)


def to_pdf(content: dict, path: Path) -> None:
    from reportlab.lib.pagesizes import A4
    from reportlab.lib.styles import getSampleStyleSheet
    from reportlab.platypus import Paragraph, SimpleDocTemplate, Spacer
    from xml.sax.saxutils import escape
    st = getSampleStyleSheet()
    doc = SimpleDocTemplate(str(path), pagesize=A4, title="TraceLine investigation report", leftMargin=48, rightMargin=48, topMargin=48, bottomMargin=48)
    flow = []
    for line in to_markdown(content).split("\n"):
        if not line.strip():
            flow.append(Spacer(1, 5))
            continue
        clean = escape(re.sub(r"[*`]", "", line)).replace("“", '"').replace("”", '"').replace("—", "-").replace("±", "+/-").replace("…", "...").replace("·", "|")
        if line.startswith("# "):
            flow.append(Paragraph(clean[2:], st["Title"]))
        elif line.startswith("## "):
            flow.append(Paragraph(clean[3:], st["Heading2"]))
        else:
            flow.append(Paragraph(clean, st["BodyText"]))
    doc.build(flow)
